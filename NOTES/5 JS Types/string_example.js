// JavaScript String Examples

let greeting = "Hello, World!";
console.log("Greeting:", greeting);

// String length
console.log("Length:", greeting.length);

// Uppercase
console.log("Uppercase:", greeting.toUpperCase());

// Substring
console.log("Substring (0,5):", greeting.substring(0, 5));

// Replace
let newGreeting = greeting.replace("World", "JavaScript");
console.log("Replaced:", newGreeting);

// Split
let words = greeting.split(", ");
console.log("Split:", words);
